#!/bin/bash

set -e
scriptdir="$( cd "$(dirname "$0")" ; pwd -P )"

#
#   Work out the OS so that we can change actions per OS where necessary.
#
shopt -s nocasematch
case "$(uname -a)" in
  *darwin*)
    OS="mac"
    ;;
  *linux*)
    OS="linux"
    ;;
  cygwin*|mingw32*|msys*|mingw*)
    OS="windows"
    ;;
  *)
    OS="unknown"
    ;;
esac

VERBOSE_FLAGS=
HELP=false

#
#   Work out which options are on the command line.
#
for i in "$@"
do
case $i in
    -v|--verbose)
    VERBOSE_FLAGS=--verbose
    ;;
    -h|--help)
    HELP=true
    ;;
    *)
    printf "Unknown command line option ($i).\n"
    printf "Run run-checks.sh --help for information on valid options.\n"
    exit 1
    ;;
esac
done

if $HELP; then
    echo "$0: Run code checks."
    echo ""
    echo "Options:"
    echo "-h | --help             Display this message"
    echo "-v | --verbose          Execute in verbose mode (useful for debugging)"
    echo ""
    exit 0
fi


SOURCE_DIR=$scriptdir
COMPONENTS_DIR=$SOURCE_DIR/components/F7Services

echo "Running cppcheck"

#
#   CLion builds each CMake profile into its own cmake-build-<profile> directory.  These hold CMake's
#   compiler identification sources, which cppcheck cannot parse, so skip any that exist.
#
CMAKE_BUILD_EXCLUDES=
for directory in cmake-build-*/
do
    if [ -d "$directory" ]; then
        CMAKE_BUILD_EXCLUDES+=" -i${directory%/}"
    fi
done

cppcheck --error-exitcode=1 --quiet --check-level=exhaustive --force --inline-suppr -iCMakeLists.txt -imanaged_components -ibuild $CMAKE_BUILD_EXCLUDES .

#
#   Our code is everything under these directories; third party code (managed_components) and
#   build output live elsewhere.  Every C and C++ source and header is checked, so a new
#   subdirectory or file type is picked up without changing this list.  build_info.h is
#   generated by build.sh from build_info.template and is not ours to format.
#
FORMAT_DIRECTORIES=("$COMPONENTS_DIR" "$SOURCE_DIR/main" "$SOURCE_DIR/test/main" "$SOURCE_DIR/Desktop")

echo "Running clang-format"
FORMAT_FILES=()
while IFS= read -r -d '' file
do
    FORMAT_FILES+=("$file")
done < <(find "${FORMAT_DIRECTORIES[@]}" -type f \( -name '*.c' -o -name '*.h' -o -name '*.cpp' -o -name '*.hpp' \) ! -name build_info.h -print0 | sort -z)

if [ ${#FORMAT_FILES[@]} -eq 0 ]; then
    echo "No source files found to check."
    exit 1
fi
clang-format --dry-run --Werror $VERBOSE_FLAGS "${FORMAT_FILES[@]}"
