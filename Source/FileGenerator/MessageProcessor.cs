        #region C# extract function code generation

        /// <summary>
        /// Generate the method that can extract the specified message.
        /// </summary>
        /// <param name="sourceFile">Output stream for the C# file that will hold the extract method.</param>
        /// <param name="message">Message defintion to be extracted.</param>
        private void GenerateCSharpExtractFunction(StreamWriter sourceFile, Message message)
        {
            string variableName = message.Name.Substring(0, 1).ToLower() + message.Name.Substring(1);
            sourceFile.WriteLine();
            sourceFile.WriteLine("        /// <summary>");
            sourceFile.WriteLine($"        /// Extract a {message.Name} object from a byte array.");
            sourceFile.WriteLine("        /// </summary>");
            sourceFile.WriteLine($"        /// <param name=\"{variableName}\">Byte array containing the object to the extracted.</param>");
            sourceFile.WriteLine($"        /// <returns>{message.Name} object.</returns>");
            sourceFile.WriteLine($"        public static MessagePayloads.{message.Name} Extract{message.Name}(byte[] buffer, int offset)");
            sourceFile.WriteLine("        {");
            sourceFile.WriteLine($"            {message.Name} {variableName} = new MessagePayloads.{message.Name}();");
            sourceFile.WriteLine();
            for (var index = 0; index < message.MessageElements.Count; index++)
            {
                MessageElement me = message.MessageElements[index];
                string sizeModifier = "";
                DataType dt = GetDataType(me.DataType);
                switch (dt.Name.ToLower())
                {
                    case "byte":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = buffer[offset];");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                    case "sbyte":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = (sbyte) buffer[offset];");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                    case "fixedbytearray":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = new byte[{me.Length}];");
                        sourceFile.WriteLine($"            Array.Copy(buffer, offset, {variableName}.{me.Name}, 0, {me.Length});");
                        sizeModifier = $"            offset += (int) {me.Length};";
                        break;
                    case "fixedchararray":
                        sourceFile.WriteLine($"            for (int index = 0; (buffer[index + offset] != 0) && (index < ({me.Length} - 1)); index++)");
                        sourceFile.WriteLine("            {");
                        sourceFile.WriteLine($"                {variableName}.{me.Name} += Convert.ToChar(buffer[index + offset]);");
                        sourceFile.WriteLine("            }");
                        sizeModifier = $"            offset += (int) {me.Length};";
                        break;
                    case "blob":
                        sourceFile.WriteLine($"            {variableName}.{me.Name}Length = ExtractUInt32(buffer, offset);");
                        sourceFile.WriteLine($"            offset += 4;");
                        sourceFile.WriteLine($"            if ({variableName}.{me.Name}Length > 0)");
                        sourceFile.WriteLine("            {");
                        sourceFile.WriteLine($"                {variableName}.{me.Name} = new byte[{variableName}.{me.Name}Length];");
                        sourceFile.WriteLine($"                Array.Copy(buffer, offset, {variableName}.{me.Name}, 0, {variableName}.{me.Name}Length);");
                        if (index < (message.MessageElements.Count - 1))
                        {
                            sourceFile.WriteLine($"                offset += (int) {variableName}.{me.Name}Length;");
                        }
                        sourceFile.WriteLine("            }");
                        break;
                    case "string":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = Extract{dt.CSharpTypeName}(buffer, offset);");
                        sizeModifier = $"            offset += (int) ({variableName}.{me.Name}.Length + 1);";
                        break;
                    case "structure":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = Extract{me.CSName}(buffer, offset);");
                        sizeModifier = $"            offset += Encoded{me.CSName}BufferSize({variableName}.{me.Name});";
                        break;
                    case "pointer":
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = ExtractUInt32(buffer, offset);");
                        sizeModifier = $"            offset += 4;";
                        break;
                    default:
                        sourceFile.WriteLine($"            {variableName}.{me.Name} = Extract{dt.CSharpTypeName}(buffer, offset);");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                }
                if (index < (message.MessageElements.Count - 1))
                {
                    if (!string.IsNullOrEmpty(sizeModifier))
                    {
                        sourceFile.WriteLine(sizeModifier);
                    }
                }
            }
            sourceFile.WriteLine($"            return({variableName});");
            sourceFile.WriteLine("        }");
            sourceFile.WriteLine();
        }

        #endregion C# extract function code generation

        // <summary>
        /// Generate the C# file that will hold the C# methods for encoding and extracting
        /// messages.
        /// </summary>
        /// <param name="messages">List of messages to process.</param>
        private void GenerateCSharpEncodersFile(IList<Message> messages)
        {
            using (StreamWriter sourceFile = new StreamWriter($"{OutputDirectory}Encoders.cs"))
            {
                OutputCSharpFileHeader(sourceFile);
                sourceFile.WriteLine("namespace Meadow.Devices.Esp32.MessagePayloads");
                sourceFile.WriteLine("{");
                sourceFile.WriteLine("    public static class Encoders");
                sourceFile.WriteLine("    {");
                using (StreamReader templateFile = new StreamReader($"{MetadataDirectory}Encoders.cs.txt"))
                {
                    sourceFile.Write(templateFile.ReadToEnd());
                }

                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        GenerateCSharpEncoderFunction(sourceFile, m);
                        GenerateCSharpExtractFunction(sourceFile, m);
                        GenerateCSharpMessageEncodedBufferSizeFunction(sourceFile, m);
                    }
                }
                sourceFile.WriteLine("    }");
                sourceFile.WriteLine("}");
            }
        }

        /// <summary>
        /// Output the structure C# definitions for the list of messages.
        /// </summary>
        /// <param name="messages">List of messages to convert into structure definitions.</param>
        private void GenerateCSharpMessageStructureFile(IList<Message> messages)
        {
            using (StreamWriter file = new StreamWriter($"{OutputDirectory}Messages.cs"))
            {
                OutputCSharpFileHeader(file);
                file.WriteLine("namespace Meadow.Devices.Esp32.MessagePayloads");
                file.WriteLine("{");
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        file.WriteLine($"    public struct {m.Name}");
                        file.WriteLine("    {");
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DataType);
                            switch (dt.Name.ToLower())
                            {
                                case "blob":
                                    file.WriteLine($"        public UInt32 {me.Name}Length;");
                                    file.WriteLine($"        public {dt.CSharpTypeName} {me.Name};");
                                    break;
                                case "fixedchararray":
                                    //
                                    //  Fixed chars are actually encoded as normal strings in C#.
                                    //
                                    file.WriteLine($"        public {dt.CSharpTypeName} {me.Name};");
                                    break;
                                case "fixedbytearray":
                                    file.WriteLine($"        public {dt.CSharpTypeName}[] {me.Name};");
                                    break;
                                case "structure":
                                    file.WriteLine($"        public {me.CSName} {me.Name};");
                                    break;
                                case "pointer":
                                    file.WriteLine($"        public UInt32 {me.Name};");
                                    break;
                                default:
                                    file.WriteLine($"        public {dt.CSharpTypeName} {me.Name};");
                                    break;
                            }
                        }
                    }
                    file.WriteLine("    };");
                    file.WriteLine();
                }
                file.WriteLine("}");
            }
        }

