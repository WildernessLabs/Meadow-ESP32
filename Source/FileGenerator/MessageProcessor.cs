        /// <summary>
        /// Generate the code necessary to exract a filed of a built in type (UInt32 / Int32 etc.).
        /// </summary>
        /// <param name="sourceFile">Existing StreamWriter object for the source file being created.</param>
        /// <param name="variableName">Variable holding the extracted message</param>
        /// <param name="fieldName">Field / member of the message structure holding the data item.</param>
        /// <param name="dataType">DataType object holding information about the item (field) being extracted.</param>
        /// <param name="language">Is this a C or C++ file?</param>
        /// <returns>String holding the code necessary to move the buffer on according to the amount of data that has been extracted.</returns>
        private string WriteDefaultObjectExtractCode(StreamWriter sourceFile, string variableName, string fieldName, DataType dataType, Language language)
        {
            if (language == Language.Cpp)
            {
                sourceFile.WriteLine($"    {variableName}->{fieldName} = Extract{dataType.CSharpTypeName}(buffer);");
            }
            else
            {
                sourceFile.WriteLine($"    {variableName}->{fieldName} = espcp_extract_{ConvertNameToCStyleName(dataType.CSharpTypeName).Replace("_", "")}(buffer);");
            }
            return($"    buffer += {dataType.Size};");
        }

        /// <summary>
        /// Generate the method that will extract an encoded message and place the data in
        /// the appropriate fields in the structure.
        /// </summary>
        /// <param name="sourceFile">Existing StreamWriter object for the source file being created.</param>
        /// <param name="message">Message defintion to encode.</param>
        /// <param name="language">Is this a C or C++ file?</param>
        private void GenerateCMessageExtractFunction(StreamWriter sourceFile, Message message, Language language)
        {
            string variableName;
            string typeName;
            if (language == Language.Cpp)
            {
                variableName = message.Name.Substring(0, 1).ToLower() + message.Name.Substring(1);
                typeName = message.Name;
            }
            else
            {
                variableName = ConvertNameToCStyleName(message.Name);
                typeName = variableName;
            }
            WriteCExtractFunctionHeader(sourceFile, typeName, variableName, language);
            for (var index = 0; index < message.MessageElements.Count; index++)
            {
                MessageElement me = message.MessageElements[index];
                DataType dt = GetDataType(me.DataType);
                string sizeModifier = "";
                string fieldName;
                if (language == Language.Cpp)
                {
                    fieldName = me.Name;
                }
                else
                {
                    fieldName = ConvertNameToCStyleName(me.Name);
                }
                switch (dt.Name.ToLower())
                {
                    case "byte":
                        sizeModifier = WriteByteExtractCode(sourceFile, variableName, fieldName, dt, language);
                        break;
                    case "sbyte":
                        sizeModifier = WriteSByteExtractCode(sourceFile, variableName, fieldName, dt, language);
                        break;
                    case "string":
                        sizeModifier = WriteStringExtractCode(sourceFile, variableName, fieldName, dt, language);
                        break;
                    case "fixedchararray":
                    case "fixedbytearray":
                        WriteFixedByteArrayExtractCode(sourceFile, variableName, fieldName, (int) me.Length, language);
                        sizeModifier = $"    buffer += {me.Length};";
                        break;
                    case "blob":
                        WriteBlobExtractCode(sourceFile, variableName, fieldName, dt, language);
                        break;
                    case "structure":
                        sizeModifier = WriteStructureExtractCode(sourceFile, variableName, fieldName, me.CSName, language);
                        break;
                    case "pointer":
                        WritePointerExtractCode(sourceFile, variableName, fieldName, me.CName, language);
                        sizeModifier = $"    buffer += {dt.Size};";
                        break;
                    default:
                        sizeModifier = WriteDefaultObjectExtractCode(sourceFile, variableName, fieldName, dt, language);
                        break;
                }
                if (index < (message.MessageElements.Count - 1))
                {
                    if (!string.IsNullOrEmpty(sizeModifier))
                    {
                        sourceFile.WriteLine(sizeModifier);
                    }
                }
            }
            sourceFile.WriteLine($"    return({variableName});");
            sourceFile.WriteLine("}");
            sourceFile.WriteLine();
        }

        #endregion C/C++ extract code generation methods

        /// <summary>
        /// Generate the message encoders / extract and encoded message size methods
        /// for the list of messages.
        /// </summary>
        /// <param name="messages">List of messages to process.</param>
        /// <param name="language">Is this a C or C++ file?</param>
        private void GenerateCMessagesEncoders(IList<Message> messages, Language language)
        {
            _functionPrototypes = new StringBuilder();
            string postfix = "";
            string sourceFileName;
            if (language == Language.Cpp)
            {
                sourceFileName = $"{OutputDirectory}Encoders.cpp";
                postfix = "pp";
            }
            else
            {
                sourceFileName = $"{OutputDirectory}espcp_encoders.c";
            }
            using (StreamWriter file = new StreamWriter(sourceFileName))
            {
                // OutputCHeaderFileHeader(file, sourceFileName, language);
                file.WriteLine();
                if (language == Language.Cpp)
                {
                    file.WriteLine($"#include \"Encoders.hpp\"");
                }
                else
                {
                    file.WriteLine($"#include \"espcp_encoders.h\"");
                }
                file.WriteLine();
                using (StreamReader templateFile = new StreamReader($"{MetadataDirectory}Encoders.c{postfix}.txt"))
                {
                    file.Write(templateFile.ReadToEnd());
                }
                file.WriteLine();
                file.WriteLine("/*");
