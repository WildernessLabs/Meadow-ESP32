        /// <summary>
        /// Output the structure C definitions for the list of messages.
        /// </summary>
        /// <param name="messages">List of messages to convert into structure definitions.</param>
        /// <param name="language">Is this a C or C++ file?</param>
        private void GenerateCMessageStructureFile(IList<Message> messages, Language language)
        {
            string outputFileName;
            if (language == Language.Cpp)
            {
                outputFileName = $"{OutputDirectory}Encoders.hpp";
            }
            else
            {
                outputFileName = $"{OutputDirectory}espcp_encoders.h";
            } 
            using (StreamWriter sourceFile = new StreamWriter(outputFileName))
            {
                WriteCHeaderFileHeader(sourceFile, outputFileName, language);
                //
                //  Write the structures defined in the meta data.
                //
                string indent = "";
                if (language == Language.Cpp)
                {
                    indent = "    ";
                }
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        string structureName;
                        string fullStructureName;
                        if (language == Language.Cpp)
                        {
                            structureName = m.Name;
                            fullStructureName = m.Name;
                        }
                        else
                        {
                            structureName = $"espcp_{ConvertNameToCStyleName(m.Name)}";
                            fullStructureName = $"espcp_{ConvertNameToCStyleName(m.Name)}_s";
                            
                        }
                        sourceFile.WriteLine($"{indent}struct {fullStructureName}");
                        sourceFile.WriteLine($"{indent}{{");
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DataType);
                            string fieldName;
                            if (language == Language.Cpp)
                            {
                                fieldName = me.Name;
                            }
                            else
                            {
                                fieldName = ConvertNameToCStyleName(me.Name);
                            }
                            switch (dt.Name.ToLower())
                            {
                                case "blob":
                                    if (language == Language.Cpp)
                                    {
                                        sourceFile.WriteLine($"        uint32_t {fieldName}Length;");
                                    }
                                    else
                                    {
                                        sourceFile.WriteLine($"    uint32_t {fieldName}_length;");
                                    }
                                    sourceFile.WriteLine($"{indent}    uint8_t *{fieldName};");
                                    break;
                                case "fixedchararray":
                                case "fixedbytearray":
                                    sourceFile.WriteLine($"{indent}    {dt.CTypeName} {fieldName}[{me.Length}];");
                                    break;
                                case "structure":
                                    sourceFile.WriteLine($"{indent}    {me.CName} {fieldName};");
                                    break;
                                case "pointer":
                                    sourceFile.WriteLine($"{indent}    void *{fieldName};");
                                    break;
                                default:
                                    sourceFile.WriteLine($"{indent}    {dt.CTypeName} {fieldName};");
                                    break;
                            }
                        }
                        sourceFile.WriteLine($"{indent}}};");
                        if (language == Language.C)
                        {
                            sourceFile.WriteLine($"typedef struct {fullStructureName} {structureName}_t;");
                        }
                        sourceFile.WriteLine();
                    }
                }
                //
                //  Add the static entries for message definitions etc. from the template file.
                //
                string templateFileName;
                if (language == Language.Cpp)
                {
                    templateFileName = MetadataDirectory + "Encoders.hpp.txt";
                    sourceFile.WriteLine("}");
                }
                else
                {
                    templateFileName = MetadataDirectory + "Encoders.h.txt";
                }
                sourceFile.WriteLine();
