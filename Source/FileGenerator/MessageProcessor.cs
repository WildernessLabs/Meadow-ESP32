        /// <summary>
        /// Generate the method that will cencode the specified message.
        /// </summary>
        /// <param name="sourceFile">Output stream for the C# file that will hold the encoder.</param>
        /// <param name="message">Message defintion to encode.</param>
        private void GenerateCSharpEncoderFunction(StreamWriter sourceFile, Message message)
        {
            string variableName = message.Name.Substring(0, 1).ToLower() + message.Name.Substring(1);
            sourceFile.WriteLine("        /// <summary>");
            sourceFile.WriteLine($"        /// Encode a {message.Name} object and return a byte array containing the encoded message.");
            sourceFile.WriteLine("        /// </summary>");
            sourceFile.WriteLine($"        /// <param name=\"{variableName}\">{message.Name} object to be encoded.</param>");
            sourceFile.WriteLine($"        /// <returns>Byte array containing the encoded {message.Name} object.</returns>");
            sourceFile.WriteLine($"        public static byte[] Encode{message.Name}(MessagePayloads.{message.Name} {variableName})");
            sourceFile.WriteLine("        {");
            sourceFile.WriteLine("            int offset = 0;");
            sourceFile.WriteLine("            int length = 0;");
            sourceFile.WriteLine();
            sourceFile.WriteLine("            //");
            sourceFile.WriteLine("            //  Calculate the amount of memory needed.");
            sourceFile.WriteLine("            //");
            int nonStringLength = 0;
            foreach (MessageElement me in message.MessageElements)
            {
                DataType dt = GetDataType(me.DataType);
                switch (dt.Name.ToLower())
                {
                    case "string":
                        sourceFile.WriteLine($"            length += (int) ({variableName}.{me.Name}.Length + 1);");
                        break;
                    case "fixedbytearray":
                    case "fixedchararray":
                        sourceFile.WriteLine($"            length += (int) {me.Length};");
                        break;
                    case "blob":
                        sourceFile.WriteLine($"            length += (int) ({variableName}.{me.Name}Length + 4);");
                        break;
                    case "structure":
                        sourceFile.WriteLine($"            length += Encoded{me.Name}BufferSize();");
                        break;
                    default:
                        nonStringLength += dt.Size;
                        break;
                }
            }
            if (nonStringLength != 0)
            {
                sourceFile.WriteLine($"            length += {nonStringLength};");
            }
            sourceFile.WriteLine();
            sourceFile.WriteLine("            //");
            sourceFile.WriteLine("            //  Now allocate a new buffer and copy the data in to the buffer.");
            sourceFile.WriteLine("            //");
            sourceFile.WriteLine($"            byte[] buffer = new byte[length];");

            sourceFile.WriteLine($"            Array.Clear(buffer, 0, buffer.Length);");
            bool amountDeclared = false;
            for (var index = 0; index < message.MessageElements.Count; index++)
            {
                MessageElement me = message.MessageElements[index];
                string sizeModifier = "";
                DataType dt = GetDataType(me.DataType);
                switch (dt.Name.ToLower())
                {
                    case "byte":
                        sourceFile.WriteLine($"            buffer[offset] = {variableName}.{me.Name};");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                    case "sbyte":
                        sourceFile.WriteLine($"            buffer[offset] = (byte) {variableName}.{me.Name};");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                    case "fixedbytearray":
                        sourceFile.WriteLine($"            Array.Copy({variableName}.{me.Name}, 0, buffer, offset, {me.Length});");
                        sizeModifier = $"            offset += (int) {me.Length};";
                        break;
                    case "fixedchararray":
                        if (amountDeclared)
                        {
                            sourceFile.WriteLine($"            amount = {variableName}.{me.Name}.Length >= {me.Length} ? {me.Length} - 1 : {variableName}.{me.Name}.Length;");
                        }
                        else
                        {
                            sourceFile.WriteLine($"            int amount = {variableName}.{me.Name}.Length >= {me.Length} ? {me.Length} - 1 : {variableName}.{me.Name}.Length;");
                            amountDeclared = true;
                        }
                        sourceFile.WriteLine($"            for (int index = 0; index < amount; index++)");
                        sourceFile.WriteLine("            {");
                        sourceFile.WriteLine($"                buffer[index] = (byte) {variableName}.{me.Name}[index];");
                        sourceFile.WriteLine("            }");
                        sourceFile.WriteLine($"            buffer[amount] = 0;");
                        sizeModifier = $"            offset += (int) {me.Length};";
                        break;
                    case "blob":
                        sourceFile.WriteLine($"            EncodeUInt32({variableName}.{me.Name}Length, buffer, offset);");
                        sourceFile.WriteLine($"            offset += 4;");
                        sourceFile.WriteLine($"            if ({variableName}.{me.Name}Length > 0)");
                        sourceFile.WriteLine("            {");
                        sourceFile.WriteLine($"                Array.Copy({variableName}.{me.Name}, 0, buffer, offset, {variableName}.{me.Name}Length);");
                        if (index < (message.MessageElements.Count - 1))
                        {
                            sourceFile.WriteLine($"                offset += (int) ({variableName}.{me.Name}Length);");
                        }
                        sourceFile.WriteLine("            }");
                        break;
                    case "string":
                        sourceFile.WriteLine($"            Encode{dt.CSharpTypeName}({variableName}.{me.Name}, buffer, offset);");
                        sizeModifier = $"            offset += {variableName}.{me.Name}.Length + 1;";
                        break;
                    case "structure":
                        sourceFile.WriteLine($"            Encode{me.CSName} = Encode{me.CSName}({variableName}.{me.Name}, buffer, offset);");
                        sizeModifier = $"            offset += Encoded{me.CSName}BufferSize({variableName}.{me.Name});";
                        break;
                    case "pointer":
                        sourceFile.WriteLine($"            EncodeUInt32({variableName}.{me.Name}, buffer, offset);");
                        sizeModifier = $"            offset += 4;";
                        break;
                    default:
                        sourceFile.WriteLine($"            Encode{dt.CSharpTypeName}({variableName}.{me.Name}, buffer, offset);");
                        sizeModifier = $"            offset += {dt.Size};";
                        break;
                }
                if (index < (message.MessageElements.Count - 1))
                {
                    if (!string.IsNullOrEmpty(sizeModifier))
                    {
                        sourceFile.WriteLine(sizeModifier);
                    }
                }
            }
            sourceFile.WriteLine("            return(buffer);");
            sourceFile.WriteLine("        }");
        }

