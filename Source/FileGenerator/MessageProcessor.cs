using System;
using System.IO;
using System.Text;
using System.Collections.Generic;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace FileGenerator
{
    public class MessageProcessor
    {
        DataType[] _dataTypes = 
        {
            new DataType("uint32", 4, "uint32_t", "UInt32"),
            new DataType("int", 4, "int32_t", "Int32"),
            new DataType("byte", 1, "uint8_t", "Uint8"),
            new DataType("array", -1, "void *", "byte[]")
        };

        public string InputFileName { get; set; }

        public string CSourceFileName { get; set; }

        public string CHeaderFileName { get; set; }

        public string CSharpFileName { get; set; }

        public string CSharpStructureFileName { get; set; }

        public string CHeaderTemplateFileName { get; set; }

        public string CSourceTemplateFileName { get; set; }

        private StringBuilder FunctionPrototypes = null;


        public MessageProcessor()
        {
        }

        private DataType GetDataType(string elementDataType)
        {
            DataType result = null;

            for (int index = 0; index < _dataTypes.Length; index++)
            {
                if (_dataTypes[index].Name.ToLower() == elementDataType.ToLower())
                {
                    result = _dataTypes[index];
                }
            }
            return(result);
        }

        private void OutputCSharpFileHeader(StreamWriter outputFile)
        {
            outputFile.WriteLine("//");
            outputFile.WriteLine($"//      {Path.GetFileName(CSharpFileName)}");
            outputFile.WriteLine("//");
            outputFile.WriteLine("//      Message encoders and decoders.");
            outputFile.WriteLine("//");
            outputFile.WriteLine("//      *************************** WARNING ***************************");
            outputFile.WriteLine("//");
            outputFile.WriteLine("//      THIS FILE IS AUTOMATICALLY GENERATED.  DO NOT EDIT THIS FILE AS");
            outputFile.WriteLine("//      CHANGES WILL BE OVERWRITTEN.");
            outputFile.WriteLine("//");
            outputFile.WriteLine("//      *************************** WARNING ***************************");
            outputFile.WriteLine("//");
            outputFile.WriteLine("");
            outputFile.WriteLine("using System;");
            outputFile.WriteLine("");
        }
        private void OutputCSharpFileFooter(StreamWriter outputFile)
        {
            outputFile.WriteLine("    }");
            outputFile.WriteLine("}");
        }

        private void OutputCHeaderFileHeader(StreamWriter outputFile, string fileName)
        {
            outputFile.WriteLine("/*");
            outputFile.WriteLine($" *      {Path.GetFileName(fileName)}");
            outputFile.WriteLine(" *");
            outputFile.WriteLine(" *      Message encoders and decoders.");
            outputFile.WriteLine(" *");
            outputFile.WriteLine(" *      *************************** WARNING ***************************");
            outputFile.WriteLine(" *");
            outputFile.WriteLine(" *      THIS FILE IS AUTOMATICALLY GENERATED.  DO NOT EDIT THIS FILE AS");
            outputFile.WriteLine(" *      CHANGES WILL BE OVERWRITTEN.");
            outputFile.WriteLine(" *");
            outputFile.WriteLine(" *      NOTE THAT THIS FILE RELIES UPON THE BASIC ENCODERS FOUND IN THE");
            outputFile.WriteLine(" *      Encoders.cpp FILE.");
            outputFile.WriteLine(" *");
            outputFile.WriteLine(" *      *************************** WARNING ***************************");
            outputFile.WriteLine(" */");
            outputFile.WriteLine();
        }

        public int OutputEncoderFunctionBody(StreamWriter file, string indent, string variableName, MessageElement me, int offset)
        {
            DataType dt = GetDataType(me.DateType);
            file.WriteLine($"{indent}Encode{dt.CSharpTypeName}({variableName}.{me.Name}, buffer, offset + {offset});");
            return(dt.Size);
        }

        public int OutputDecoderFunctionBody(StreamWriter file, string indent, string variableName, MessageElement me, int offset)
        {
            DataType dt = GetDataType(me.DateType);
            file.WriteLine($"{indent}{me.Name} = Extract{dt.CSharpTypeName}(buffer, offset + {offset});");
            return(dt.Size);
        }

        private void GenerateCSharpEncodersFile(IList<Message> messages)
        {
            using (StreamWriter sourceFile = new StreamWriter(CSharpFileName))
            {
                OutputCSharpFileHeader(sourceFile);
                sourceFile.WriteLine("namespace UartTransport");
                sourceFile.WriteLine("{");
                sourceFile.WriteLine("    public class Encoders");
                sourceFile.WriteLine("    {");
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        sourceFile.WriteLine($"        public static void Encode{m.Name}({m.Name} {variableName}, byte[] buffer, int offset)");
                        sourceFile.WriteLine("        {");
                        int offset = 0;
                        foreach (MessageElement me in m.MessageElements)
                        {
                            offset += OutputEncoderFunctionBody(sourceFile, "            ", variableName, me, offset);
                        }
                        sourceFile.WriteLine("        }");
                        sourceFile.WriteLine();
                        sourceFile.WriteLine($"        public static {m.Name} *Extract{m.Name}(byte[] buffer, int offset)");
                        sourceFile.WriteLine("        {");
                        sourceFile.WriteLine($"            {m.Name} {variableName};");
                        sourceFile.WriteLine();
                        offset = 0;
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DateType);
                            sourceFile.WriteLine($"        {variableName}.{me.Name} = Extract{dt.CSharpTypeName}(buffer, offset + {offset});");
                            offset += dt.Size;
                        }
                        sourceFile.WriteLine($"            return({variableName});");
                        sourceFile.WriteLine("        }");
                        sourceFile.WriteLine();
                    }
                }
                sourceFile.WriteLine("    }");
                sourceFile.WriteLine("}");
            }
        }

        private void GenerateCSharpMessageStructureFile(IList<Message> messages)
        {
            using (StreamWriter sourceFile = new StreamWriter(CSharpStructureFileName))
            {
                OutputCSharpFileHeader(sourceFile);
                sourceFile.WriteLine("namespace Esp32Messaging");
                sourceFile.WriteLine("{");
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        sourceFile.WriteLine($"    public struct {m.Name}");
                        sourceFile.WriteLine("    {");
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DateType);
                            sourceFile.WriteLine($"        {dt.CSharpTypeName} {me.Name};");                         
                        }
                    }
                    sourceFile.WriteLine("    };");
                    sourceFile.WriteLine();
                }
                sourceFile.WriteLine("}");
            }
        }

        private void GenerateCMessageStructureFile(IList<Message> messages)
        {
            using (StreamWriter sourceFile = new StreamWriter(CHeaderFileName))
            {
                OutputCHeaderFileHeader(sourceFile, CHeaderFileName);
                sourceFile.WriteLine("#ifndef _ENCODERS_HPP_");
                sourceFile.WriteLine("#define _ENCODERS_HPP_");
                sourceFile.WriteLine();
                sourceFile.WriteLine("#include \"freertos/FreeRTOS.h\"");
                sourceFile.WriteLine();
                sourceFile.WriteLine("namespace Esp32Messaging");
                sourceFile.WriteLine("{");
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        sourceFile.WriteLine($"    struct {m.Name}");
                        sourceFile.WriteLine("    {");
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DateType);
                            sourceFile.WriteLine($"        {dt.CTypeName} {me.Name};");                         
                        }
                        sourceFile.WriteLine("    };");
                        sourceFile.WriteLine();
                    }
                }
                sourceFile.WriteLine("}");
                sourceFile.WriteLine();
                using (StreamReader templateFile = new StreamReader(CHeaderTemplateFileName))
                {
                    sourceFile.Write(templateFile.ReadToEnd());
                }
                sourceFile.WriteLine(FunctionPrototypes.ToString());
                sourceFile.WriteLine("};");
                sourceFile.WriteLine();
                sourceFile.WriteLine("  #endif /* _ENCODERS_HPP_ */");
                sourceFile.WriteLine();
            }
        }

        private void GenerateCMessagesEncoders(IList<Message> messages)
        {
            FunctionPrototypes = new StringBuilder();
            using (StreamWriter sourceFile = new StreamWriter(CSourceFileName))
            {
                OutputCHeaderFileHeader(sourceFile, CSourceFileName);
                sourceFile.WriteLine();
                sourceFile.WriteLine("#include \"Encoders.hpp\"");
                sourceFile.WriteLine();
                using (StreamReader templateFile = new StreamReader(CSourceTemplateFileName))
                {
                    sourceFile.Write(templateFile.ReadToEnd());
                }
                sourceFile.WriteLine();
                sourceFile.WriteLine("/*");
                sourceFile.WriteLine(" *******************************************************************************");
                sourceFile.WriteLine();
                sourceFile.WriteLine("       THE METHODS BELOW HAVE BEEN AUTOMATICALLY GENERATED BASED UPON THE");
                sourceFile.WriteLine("       Messages.json METADATA FILE.");
                sourceFile.WriteLine();
                sourceFile.WriteLine(" *******************************************************************************");
                sourceFile.WriteLine("*/");
                foreach (Message m in messages)
                {
                    if (m.MessageElements != null)
                    {
                        string variableName = m.Name.Substring(0, 1).ToLower() + m.Name.Substring(1);
                        sourceFile.WriteLine($"void Encoders::Encode{m.Name}(Esp32Messaging::{m.Name} *{variableName}, uint8_t *buffer, int offset)");
                        FunctionPrototypes.AppendLine($"    static void Encode{m.Name}(Esp32Messaging::{m.Name} *, uint8_t *, int);");
                        sourceFile.WriteLine("{");
                        int offset = 0;
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DateType);
                            if (dt.CTypeName.ToLower() == ("uint8_t"))
                            {
                                sourceFile.WriteLine($"    *(buffer + {offset}) = {variableName}->{me.Name};");
                            }
                            else
                            {
                                sourceFile.WriteLine($"    Encode{dt.CSharpTypeName}({variableName}->{me.Name}, (uint8_t *) (buffer + {offset}));");
                            }
                            offset += dt.Size;
                        }
                        sourceFile.WriteLine("}");
                        sourceFile.WriteLine();
                        sourceFile.WriteLine($"Esp32Messaging::{m.Name} *Encoders::Extract{m.Name}(uint8_t *buffer, int offset)");
                        FunctionPrototypes.AppendLine($"    static Esp32Messaging::{m.Name} *Extract{m.Name}(uint8_t *, int);");
                        sourceFile.WriteLine("{");
                        sourceFile.WriteLine($"    Esp32Messaging::{m.Name} *{variableName} = (Esp32Messaging::{m.Name} *) pvPortMalloc(sizeof(Esp32Messaging::{m.Name}));");
                        sourceFile.WriteLine();
                        offset = 0;
                        foreach (MessageElement me in m.MessageElements)
                        {
                            DataType dt = GetDataType(me.DateType);
                            if (dt.CTypeName.ToLower() == ("uint8_t"))
                            {
                                sourceFile.WriteLine($"    {variableName}->{me.Name} = *(buffer + {offset});");
                            }
                            else
                            {
                                sourceFile.WriteLine($"    {variableName}->{me.Name} = Extract{dt.CSharpTypeName}(buffer + {offset});");
                            }
                            offset += dt.Size;
                        }
                        sourceFile.WriteLine($"    return({variableName});");
                        sourceFile.WriteLine("}");
                        sourceFile.WriteLine();
                    }
                }
            }
        }

        public void ProcessFile()
        {
            IList<Message> messages;
            using (StreamReader structuresFile = new StreamReader(InputFileName))
            {
                string fileContents = structuresFile.ReadToEnd();
                JObject o = JObject.Parse(fileContents);

                JArray a = (JArray)o["Messages"];

                messages = a.ToObject<IList<Message>>();
            }
            GenerateCMessagesEncoders(messages);
            //
            //  The message structure header file must be generated after the message encoders file
            //  as the prototypes are built up in the GenerateCMessagesEncoders method.  The prototypes
            //  are then added to the end of the structure file. 
            //
            GenerateCMessageStructureFile(messages);
            GenerateCSharpEncodersFile(messages);
            GenerateCSharpMessageStructureFile(messages);
        }
    }
}