using System;
using System.Threading;
using Meadow;
using Meadow.Core.Esp32.Exceptions;
using Meadow.Devices;
using Meadow.Hardware;

namespace Meadow.Core.Esp32
{
    public class Coprocessor
    {
        #region Enums
        
        /// <summary>
        /// Possible debug outputs.
        /// </summary>
        [Flags]
        public enum DebugOptions : UInt32 { None = 0x00, Information = 0x01, Errors = 0x02, Full = 0xffffffff }
        
        #endregion

        #region Private member variables (fields)
        
        /// <summary>
        /// Message dispatcher for the coprocessor.
        /// </summary>
        private readonly MessageDispatcher _dispatcher;
        
        #endregion Private member variables (fields)
        
        #region Properties
        
        /// <summary>
        /// Determine how much debug output is generated.
        /// </summary>
        public DebugOptions DebugLevel{ get; set; }
        
        #endregion Properties
        
        #region Constructors
        
        /// <summary>
        /// Default constructor (private to prevent it being used).
        /// </summary>
        private Coprocessor()
        {
            
        }
        
        /// <summary>
        /// Create a new coprocessor object and specify the message dispatcher to be used to send requests
        /// to the coprocessor.
        /// </summary>
        /// <param name="dispatcher">Message dispatcher to be used to send messages to the network chip.</param>
        public Coprocessor(MessageDispatcher dispatcher)
        {
            _dispatcher = dispatcher;
        }
        
        #endregion Constructors

        #region Methods
        
        /// <summary>
        /// Get the antenna currently in use.
        /// </summary>
        /// <returns>AntennaTyes object indicating the currently selected antenna.</returns>
        /// <exception cref="CoprocessorException">Details of any error generated by the coprocessor.</exception>
        public AntennaTypes GetAntenna()
        {
            //
            //  Prepare the request and wait object.
            //
            Messages.Message getAntennaMessage;
            getAntennaMessage = new Messages.Message();
            getAntennaMessage.Interface = (byte) Esp32Interfaces.WiFi;
            getAntennaMessage.Function = (byte) WiFiFunction.GetAntenna;
            getAntennaMessage.MessageID = _dispatcher.GetNextMessageID();
            getAntennaMessage.MessageType = (byte) MessageTypes.Data;
            getAntennaMessage.Payload = null;
            getAntennaMessage.PayloadLength = 0;

            EventWaitHandle waitHandle = new AutoResetEvent(false);
            //
            //  Queue the request.
            //
            _dispatcher.Add(getAntennaMessage, waitHandle);
            //
            //  Wait for the response to be ready.
            //
            waitHandle.WaitOne();
            //
            //  Now get the response.
            //
            Messages.Message response = _dispatcher.GetResponse(getAntennaMessage.MessageID);
            StatusCodes result = (StatusCodes)response.StatusCode;
            if (result != StatusCodes.CompletedOK)
            {
                throw new CoprocessorException(result);
            }
            Messages.AntennaInfo antenna = Encoders.ExtractAntennaInfo(response.Payload, 0);
            return((AntennaTypes) antenna.Antenna);
        }

        /// <summary>
        /// Change the current antenna in use.
        /// </summary>
        /// <param name="antenna">New antenna to use.</param>
        /// <exception cref="CoprocessorException">Exception thrown if the SetAntenna method fails.</exception>
        public void SetAntenna(AntennaTypes antenna)
        {
            //
            //  Prepare the request and wait object.
            //
            Messages.Message setAntennaMessage;
            setAntennaMessage = new Messages.Message();
            setAntennaMessage.Interface = (byte) Esp32Interfaces.WiFi;
            setAntennaMessage.Function = (byte) WiFiFunction.SetAntenna;
            setAntennaMessage.MessageID = _dispatcher.GetNextMessageID();
            setAntennaMessage.MessageType = (byte) MessageTypes.Data;

            Messages.AntennaInfo antennaInfo;
            antennaInfo = new Messages.AntennaInfo();
            antennaInfo.Antenna = (byte) antenna;
            byte[] encodedAntenna = Encoders.EncodeAntennaInfo(antennaInfo);
            setAntennaMessage.Payload = encodedAntenna;
            setAntennaMessage.PayloadLength = (UInt32) encodedAntenna.Length;
            
            EventWaitHandle waitHandle = new AutoResetEvent(false);
            //
            //  Queue the request.
            //
            _dispatcher.Add(setAntennaMessage, waitHandle);
            //
            //  Wait for the response to be ready.
            //
            waitHandle.WaitOne();
            //
            //  Now get the response.
            //
            Messages.Message response = _dispatcher.GetResponse(setAntennaMessage.MessageID);
            StatusCodes result = (StatusCodes) response.StatusCode;
            if (result != StatusCodes.CompletedOK)
            {
                throw new CoprocessorException(result);
            }
        }

        /// <summary>
        /// Start the WiFi hardware and connect to the specified network.
        /// </summary>
        /// <param name="ssid">Name of the network to connect to.</param>
        /// <param name="password">Password for the network.</param>
        public NetworkInformation StartNetwork(string ssid, string password)
        {
            Messages.WiFiCredentials startNetwork = new Messages.WiFiCredentials();
            startNetwork.NetworkName = ssid;
            startNetwork.Password = password;

            Messages.Message message = new Messages.Message();
            message.Interface = (byte) Esp32Interfaces.WiFi;
            message.Function = (uint) WiFiFunction.Start;
            message.MessageID = _dispatcher.GetNextMessageID();
            message.MessageType = (byte) MessageTypes.Data;
            byte[] encodedStartMessage = Encoders.EncodeWiFiCredentials(startNetwork);
            message.Payload = encodedStartMessage;
            message.PayloadLength = (uint) encodedStartMessage.Length;

            EventWaitHandle waitHandle = new AutoResetEvent(false);
            //
            //  Queue the request.
            //
            _dispatcher.Add(message, waitHandle);
            //
            //  Wait for the response to be ready.
            //
            waitHandle.WaitOne();
            //
            //  Now get the response.
            //
            Messages.Message response = _dispatcher.GetResponse(message.MessageID);
            StatusCodes result = (StatusCodes) response.StatusCode;
            if (result != StatusCodes.CompletedOK)
            {
                throw new CoprocessorException(result);
            }
            NetworkInformation networkInformation = new NetworkInformation();
            networkInformation.ip4IpAddress[0] = response.Payload[0];
            networkInformation.ip4IpAddress[1] = response.Payload[1];
            networkInformation.ip4IpAddress[2] = response.Payload[2];
            networkInformation.ip4IpAddress[3] = response.Payload[3];
            return (networkInformation);
        }

        /// <summary>
        /// Get the list of access points.
        /// </summary>
        /// <remarks>
        /// The network must be started before this method can be called.
        /// </remarks>
        /// <returns>List of access points (or null if no access points can be found).</returns>
        /// <exception cref="CoprocessorException">Coprocessor exception is throw if there was a problem on the ESp32.</exception>
        public Messages.AccessPoint[] GetAccessPoints()
        {
            Messages.Message message = new Messages.Message();
            message.MessageType = (byte)MessageTypes.Data;
            message.Interface = (byte)Esp32Interfaces.WiFi;
            message.Function = (UInt32)WiFiFunction.GetAccessPoints;
            message.MessageID = 0x02;
            message.PayloadLength = 0;
            
            EventWaitHandle waitHandle = new AutoResetEvent(false);
            //
            //  Queue the request.
            //
            _dispatcher.Add(message, waitHandle);
            //
            //  Wait for the response to be ready.
            //
            waitHandle.WaitOne();
            //
            //  Now get the response.
            //
            Messages.Message response = _dispatcher.GetResponse(message.MessageID);
            StatusCodes result = (StatusCodes) response.StatusCode;
            if (result != StatusCodes.CompletedOK)
            {
                throw new CoprocessorException(result);
            }
            //
            //  Now get the list of access points and return the list to the application.
            //
            Messages.AccessPointList accessPointList = Encoders.ExtractAccessPointList(response.Payload, 0);
            Messages.AccessPoint[] accessPoints = new Messages.AccessPoint[accessPointList.NumberOfAccessPoints]; 
            if (accessPointList.NumberOfAccessPoints > 0)
            {
                accessPoints = new Messages.AccessPoint[accessPointList.NumberOfAccessPoints];
                for (int count = 0; count < accessPointList.NumberOfAccessPoints; count++)
                {
                    accessPoints[count] = Encoders.ExtractAccessPoint(accessPointList.AccessPoints, count * 41);
                }
            }
            else
            {
                accessPoints = null;
            }
            return (accessPoints);
        }
        
        #endregion Methods
    }
}
