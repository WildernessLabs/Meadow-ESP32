/*
 *      Process WiFi message sent through the WiFi queue.
 *
 *      The messages will be generated by the incoming UART task.
 *
 *      @param pvParameters
 *          Pointer to a list of parameters passed to the WiFi task.
 */
void WiFiTask(void *pvParameters)
{
    struct ApplicationRequest message;
    QueueHandle_t wifiQueueHandle = wifi->GetQueueHandle();
    while (true)
    {
        BaseType_t result = xQueueReceive(wifiQueueHandle, &message, portMAX_DELAY);
        if (result == pdTRUE)
        {
            wifi->DispatchRequest(&message);
        }
    }
    //
    //  We should only get here if the code in the while loop generates a fault.
    //  The documentation for FreeRTOS states that we should delete the task
    //  should we get here.
    //
    vTaskDelete(xWiFiTaskHandle);
}

/*
 *      Process the UART transmit messages received through the UART Tx queue.
 *
 *      @param pvParameters
 *          Pointer to a list of parameters passed to the UART Tx task.
 */
void UARTTxTask(void *pvParameters)
{
    QueueHandle_t txQueueHandle = uart->GetUartTransmitQueueHandle();
    TaskHandle_t txTaskHandle = uart->GetUartTransmitTaskHandle();
    while (true)
    {
        ApplicationResponse message;

        BaseType_t result = xQueueReceive(txQueueHandle, &message, portMAX_DELAY);
        if (result == pdTRUE)
        {
            uart->Send(&message);
        }
    }
    //
    //  We should only get here if the code in the while loop generates a fault.
    //  The documentation for FreeRTOS states that we should delete the task
    //  should we get here.
    //
    vTaskDelete(txTaskHandle);
}

/*
 *      Process data received data from the UART interrupt task through the UART Rx queue.
 *
 *      @param pvParameters
 *          Pointer to a list of parameters passed to the UART Rx task.
 */
void UARTRxTask(void *pvParameters)
{
    uart_event_t event;
    QueueHandle_t uartRxQueueHandle = uart->GetUartRxQueueHandle();
    QueueHandle_t uartTxQueueHandle = uart->GetUartTransmitQueueHandle();
    uint8_t* data = (uint8_t *) pvPortMalloc(UART::RxBufferSize);

    while (true)
    {
        int dataLeftToRead = 0;
        int amountToRead = 0;
        if (xQueueReceive(uartRxQueueHandle, (void *) &event, portMAX_DELAY))
        {
            memset(data, 0, UART::RxBufferSize);
            switch (event.type)
            {
                case UART_DATA:
                    dataLeftToRead = event.size;
                    while (dataLeftToRead > 0)
                    {
                        amountToRead = dataLeftToRead <= UART::RxBufferSize ? dataLeftToRead : UART::RxBufferSize;
                        memset(data, 0, UART::RxBufferSize);
                        uart_read_bytes(uart->STM32UartNumber, data, amountToRead, portMAX_DELAY);
                        uart->DecodeSerialData(data, amountToRead);
                        dataLeftToRead -= amountToRead;
                    }
                    break;
                case UART_BUFFER_FULL:
                case UART_FIFO_OVF:
                    //
                    //  Flush the input buffer in the case of a full ring buffer or a FIFO overflow.
                    //
                    uart_flush_input(uart->STM32UartNumber);
                    xQueueReset(uartRxQueueHandle);
                    break;
                default:
                    uart_flush_input(uart->STM32UartNumber);
                    xQueueReset(uartRxQueueHandle);
                    xQueueReset(uartTxQueueHandle);
                    break;
            }
        }
    }
    //
    //  We should only get here if the code in the while loop generates a fault.
    //  The documentation for FreeRTOS states that we should delete the task
    //  should we get here.
    //
    free(data);
    data = NULL;
    uart->RxCleanup();
    vTaskDelete(uart->GetUartReceiveTaskHandle());
    //uart->SetUartReceiveTaskHandle(NULL);
}
